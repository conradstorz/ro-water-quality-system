"""Tests for the code generator itself."""

import dataclasses

from ro_tools import cli, codegen, schema


def test_render_is_deterministic():
    m = schema.load()
    assert codegen.render(m) == codegen.render(m)


def test_committed_file_matches_fresh_generation():
    assert codegen.is_current(schema.load()), "run: uv run python -m ro_tools.codegen"


def test_render_has_header_and_compiles():
    text = codegen.render(schema.load())
    assert text.startswith('"""GENERATED by ro_tools.codegen')
    assert "DO NOT EDIT" in text.splitlines()[0] + text.splitlines()[1] + text.splitlines()[2]
    assert text.endswith("\n") and not text.endswith("\n\n")
    compile(text, "registers.py", "exec")


def test_write_then_is_current(tmp_path):
    m = schema.load()
    out = tmp_path / "registers.py"
    assert not codegen.is_current(m, out)
    codegen.write(m, out)
    assert codegen.is_current(m, out)
    assert b"\r\n" not in out.read_bytes()


def test_is_current_detects_a_single_changed_byte(tmp_path):
    m = schema.load()
    out = tmp_path / "registers.py"
    codegen.write(m, out)
    data = bytearray(out.read_bytes())
    data[len(data) // 2] ^= 0x01
    out.write_bytes(bytes(data))
    assert codegen.is_current(m, out) is False


def test_critical_mask_uses_or_not_sum():
    m = dataclasses.replace(schema.load(), critical_validity_bits=(0, 1, 2, 3, 7, 0))
    assert "CRITICAL_VALIDITY = ValidityBits(0x008f)" in codegen.render(m)


def test_committed_cpp_header_matches_fresh_generation():
    assert codegen.is_cpp_current(schema.load()), "run: uv run ro-tools generate"


def test_cpp_header_says_it_is_generated():
    text = codegen.render_cpp(schema.load())
    assert text.startswith("// GENERATED by ro_tools.codegen")
    assert "DO NOT EDIT" in text.splitlines()[1]
    assert text.endswith("\n") and not text.endswith("\n\n")


def test_cpp_write_then_is_current(tmp_path):
    m = schema.load()
    out = tmp_path / "ro_registers.hpp"
    assert not codegen.is_cpp_current(m, out)
    codegen.write_cpp(m, out)
    assert codegen.is_cpp_current(m, out)
    assert b"\r\n" not in out.read_bytes()


def test_cpp_is_current_detects_a_changed_register_map(tmp_path):
    m = schema.load()
    out = tmp_path / "ro_registers.hpp"
    codegen.write_cpp(m, out)
    assert codegen.is_cpp_current(dataclasses.replace(m, input_start=101), out) is False


def test_generate_check_fails_on_a_stale_cpp_header(monkeypatch, tmp_path, capsys):
    stale = tmp_path / "ro_registers.hpp"
    codegen.write_cpp(schema.load(), stale)
    stale.write_text(stale.read_text(encoding="utf-8") + "// edited\n", encoding="utf-8")
    monkeypatch.setattr(codegen, "CPP_PATH", stale)
    assert cli.main(["generate", "--check"]) == 1
    assert "ro_registers.hpp differs" in capsys.readouterr().err
